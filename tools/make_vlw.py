#!/usr/bin/env python3
"""Convert a TTF into an anti-aliased VLW font (the Processing/TFT_eSPI smooth
font format LovyanGFX understands) and emit it as a C array.

Usage: make_vlw.py OUT_HEADER  NAME:TTF:SIZE:CHARS[:OPTS]  [...]
  TTF may be "file.ttf@Bold" (named instance) or "file.ttf@600" (weight axis)
  for variable fonts. CHARS may be "ascii" for printable ASCII.
  OPTS: comma-separated track=N (extra px between glyphs), gamma=G (alpha^G;
  <1 makes anti-aliased edges fuller, which helps thin strokes on small LCDs),
  balance=1 (centre each glyph in its rounded advance, so the rounding error
  is split between both sides instead of all landing on the right; evens out
  spacing at small sizes, where e.g. a 6.47 px "T" otherwise touches its neighbour).
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont


def glyph(font, ch, track=0, gamma=1.0, balance=False):
    ascent, descent = font.getmetrics()
    size = (font.size * 3, ascent + descent + font.size)
    img = Image.new("L", size, 0)
    ox, base = font.size, ascent + font.size // 2
    exact = font.getlength(ch)
    adv = round(exact)
    shift = (adv - exact) / 2 if balance else 0  # sub-pixel offset of the outline
    ImageDraw.Draw(img).text((ox + shift, base), ch, font=font, fill=255, anchor="ls")
    adv += track
    bbox = img.getbbox()
    if bbox is None:  # space
        return dict(w=0, h=0, adv=adv, dy=0, dx=0, data=b"")
    l, t, r, b = bbox
    crop = img.crop(bbox)
    if gamma != 1.0:
        crop = crop.point(lambda a: round(255 * (a / 255) ** gamma))
    return dict(w=r - l, h=b - t, adv=adv, dy=base - t, dx=l - ox, data=crop.tobytes())


def vlw(ttf, size, chars, track=0, gamma=1.0, balance=False):
    ttf, _, weight = ttf.partition("@")  # variable-font instance: name or weight value
    font = ImageFont.truetype(ttf, size)
    if weight.isdigit():
        font.set_variation_by_axes([int(weight)])
    elif weight:
        font.set_variation_by_name(weight)
    ascent, descent = font.getmetrics()
    chars = sorted(set(chars), key=ord)
    glyphs = [(ord(c), glyph(font, c, track, gamma, balance)) for c in chars]
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for code, g in glyphs:
        out += struct.pack(">7i", code, g["h"], g["w"], g["adv"], g["dy"], g["dx"], 0)
    for _, g in glyphs:
        out += g["data"]
    return out


def main():
    header, specs = sys.argv[1], sys.argv[2:]
    lines = [
        "// Generated by tools/make_vlw.py - anti-aliased VLW fonts for LovyanGFX.",
        "// Fonts are SIL Open Font License 1.1 (see fonts/).",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for spec in specs:
        name, ttf, size, chars, *rest = spec.split(":", 4)
        opts = dict(o.split("=") for o in rest[0].split(",")) if rest else {}
        track, gamma = int(opts.get("track", 0)), float(opts.get("gamma", 1.0))
        balance = opts.get("balance", "0") == "1"
        if chars == "ascii":
            chars = "".join(chr(c) for c in range(32, 127))
        data = vlw(ttf, int(size), chars, track, gamma, balance)
        lines.append(f"// {name}: {ttf.split('/')[-1]} {size}px {rest[0] if rest else ''}, "
                     f"{len(set(chars))} glyphs, {len(data)} bytes")
        lines.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i : i + 24]) + ",")
        lines.append("};\n")
    open(header, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
